import { existsSync } from "node:fs";
import { join } from "node:path";
import type { NextConfig } from "next";
import { PHASE_PRODUCTION_BUILD } from "next/constants";
import { services, solutions } from "./lib/data";
import imageWidths from "./lib/image-widths.json";

const nextConfig: NextConfig = {
  poweredByHeader: false,
  experimental: {
    // The whole stylesheet is ~14 KB gzipped. Inlining it removes the only render-blocking request,
    // so the first frame (hero) paints without waiting on a network round trip.
    inlineCss: true,
  },
  // Photos are pre-built as static WebP files in every width below (scripts/optimize-images.mjs) and
  // served straight from the CDN. On-demand optimization took 0.4–1.2s for each size the first time
  // it was requested, which visitors saw as photos loading late.
  images: {
    loader: "custom",
    loaderFile: "./lib/image-loader.ts",
    deviceSizes: imageWidths.deviceSizes,
    imageSizes: imageWidths.imageSizes,
  },
  async headers() {
    // File names aren't content-hashed, so cache for a day and revalidate in the background after.
    const cache = [{ key: "Cache-Control", value: "public, max-age=86400, stale-while-revalidate=604800" }];
    return [
      { source: "/img/:path*", headers: cache },
      { source: "/videos/:path*", headers: cache },
    ];
  },
  // The previous WordPress site served every page from the root (/about-us/, /odc-cargo-shipping/…).
  // Send those URLs to their new homes so existing links and search results keep working.
  async redirects() {
    return [
      { source: "/about-us", destination: "/about", permanent: true },
      { source: "/contact-us", destination: "/contact", permanent: true },
      ...[...solutions, ...services].map((o) => ({ source: `/${o.slug}`, destination: o.href, permanent: true })),
    ];
  },
};

/**
 * Without the pre-built image sizes every photo would 404. They are generated by the package.json
 * build script; if a build is started some other way (plain `next build`), fail it, so the live
 * deployment stays as it is instead of being replaced by one without photos.
 */
export default function config(phase: string): NextConfig {
  if (phase === PHASE_PRODUCTION_BUILD && !existsSync(join(process.cwd(), "public/img"))) {
    throw new Error("public/img is missing. Build with `npm run build`, which generates the image sizes first.");
  }
  return nextConfig;
}
